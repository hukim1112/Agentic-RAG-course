def build_database(db_path: Path) -> None:
    db_path.parent.mkdir(parents=True, exist_ok=True)
    if db_path.exists():
        db_path.unlink()

    conn = sqlite3.connect(str(db_path))
    try:
        conn.executescript(SCHEMA_SQL)
        conn.execute("PRAGMA foreign_keys = ON;")

        # 1. Insert departments (temporarily head_emp_id is text, not FK-constrained so circular insert is clean)
        departments = get_departments()
        conn.executemany(
            """
            INSERT INTO departments (
                dept_code, dept_name, dept_alias, division_name,
                head_emp_id, annual_budget_krw, office_location
            ) VALUES (?, ?, ?, ?, ?, ?, ?);
            """,
            departments,
        )

        # 2. Insert employees (ordered so managers appear before subordinates)
        employees = get_employees()
        conn.executemany(
            """
            INSERT INTO employees (
                emp_id, name, rank, role, dept_code,
                manager_emp_id, security_clearance, hire_date, base_salary_krw
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?);
            """,
            employees,
        )

        # 3. Insert projects
        projects = get_projects()
        conn.executemany(
            """
            INSERT INTO projects (
                project_id, project_name, lead_dept_code, pm_emp_id,
                approver_emp_id, approved_budget_krw, status, risk_level,
                depends_on_project_id, start_date, end_date
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?);
            """,
            projects,
        )

        # 4. Insert project_members
        project_members = get_project_members()
        conn.executemany(
            """
            INSERT INTO project_members (
                project_id, emp_id, assigned_role, allocation_pct, joined_date
            ) VALUES (?, ?, ?, ?, ?);
            """,
            project_members,
        )

        # 5. Insert expense_transactions
        expense_transactions = get_expense_transactions()
        conn.executemany(
            """
            INSERT INTO expense_transactions (
                tx_id, project_id, requester_emp_id, approver_emp_id,
                category, destination_city, nights, amount_krw,
                approval_status, tx_date, description
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?);
            """,
            expense_transactions,
        )

        # 6. Insert gpu_cluster_allocations
        gpu_clusters = get_gpu_cluster_allocations()
        conn.executemany(
            """
            INSERT INTO gpu_cluster_allocations (
                allocation_id, project_id, managed_by_dept_code, gpu_model,
                node_count, gpus_per_node, serving_engine, kv_cache_waste_pct,
                avg_utilization_pct, monthly_cost_krw, region
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?);
            """,
            gpu_clusters,
        )

        # 7. Insert department_budgets
        department_budgets = get_department_budgets()
        conn.executemany(
            """
            INSERT INTO department_budgets (
                budget_id, fiscal_year, dept_code, account_code,
                category, allocated_krw, spent_krw, as_of_date
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?);
            """,
            department_budgets,
        )

        # 부서별 비목 편성액 합계가 부서 연간 예산과 일치하는지 확인
        mismatched = conn.execute(
            """
            SELECT d.dept_code, d.annual_budget_krw, SUM(b.allocated_krw)
            FROM departments d JOIN department_budgets b ON d.dept_code = b.dept_code
            GROUP BY d.dept_code HAVING SUM(b.allocated_krw) != d.annual_budget_krw
            """
        ).fetchall()
        if mismatched:
            raise RuntimeError(f"department_budgets 편성액 합계가 부서 연간 예산과 다릅니다: {mismatched}")

        # Verify foreign key integrity
        fk_errors = conn.execute("PRAGMA foreign_key_check;").fetchall()
        if fk_errors:
            raise RuntimeError(f"Foreign key check failed: {fk_errors}")

        conn.commit()
    finally:
        conn.close()


