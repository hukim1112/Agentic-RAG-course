SCHEMA_SQL = """
PRAGMA foreign_keys = ON;

DROP TABLE IF EXISTS department_budgets;
DROP TABLE IF EXISTS gpu_cluster_allocations;
DROP TABLE IF EXISTS expense_transactions;
DROP TABLE IF EXISTS project_members;
DROP TABLE IF EXISTS projects;
DROP TABLE IF EXISTS employees;
DROP TABLE IF EXISTS departments;

CREATE TABLE departments (
    dept_code TEXT PRIMARY KEY,
    dept_name TEXT UNIQUE NOT NULL,
    dept_alias TEXT NOT NULL,
    division_name TEXT NOT NULL,
    head_emp_id TEXT,
    annual_budget_krw INTEGER NOT NULL,
    office_location TEXT NOT NULL
);

CREATE TABLE employees (
    emp_id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    rank TEXT NOT NULL CHECK (rank IN ('전무', '상무', '수석', '책임', '선임', '전임')),
    role TEXT NOT NULL CHECK (role IN ('본부장', 'CISO', '팀장', '팀원')),
    dept_code TEXT NOT NULL,
    manager_emp_id TEXT,
    security_clearance TEXT NOT NULL CHECK (security_clearance IN ('극비', '대외비', '사내한')),
    hire_date TEXT NOT NULL,
    base_salary_krw INTEGER NOT NULL,
    FOREIGN KEY (dept_code) REFERENCES departments(dept_code),
    FOREIGN KEY (manager_emp_id) REFERENCES employees(emp_id)
);

CREATE TABLE projects (
    project_id TEXT PRIMARY KEY,
    project_name TEXT NOT NULL,
    lead_dept_code TEXT NOT NULL,
    pm_emp_id TEXT NOT NULL,
    approver_emp_id TEXT NOT NULL,
    approved_budget_krw INTEGER NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('진행중', '검토중', '완료')),
    risk_level TEXT NOT NULL CHECK (risk_level IN ('HIGH', 'MEDIUM', 'LOW')),
    depends_on_project_id TEXT,
    start_date TEXT NOT NULL,
    end_date TEXT NOT NULL,
    FOREIGN KEY (lead_dept_code) REFERENCES departments(dept_code),
    FOREIGN KEY (pm_emp_id) REFERENCES employees(emp_id),
    FOREIGN KEY (approver_emp_id) REFERENCES employees(emp_id),
    FOREIGN KEY (depends_on_project_id) REFERENCES projects(project_id)
);

CREATE TABLE project_members (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    project_id TEXT NOT NULL,
    emp_id TEXT NOT NULL,
    assigned_role TEXT NOT NULL CHECK (
        assigned_role IN ('PM', '클라우드아키텍트', 'AI엔지니어', '데이터엔지니어', '보안감리', '파견협업')
    ),
    allocation_pct INTEGER NOT NULL CHECK (allocation_pct BETWEEN 10 AND 100),
    joined_date TEXT NOT NULL,
    FOREIGN KEY (project_id) REFERENCES projects(project_id),
    FOREIGN KEY (emp_id) REFERENCES employees(emp_id),
    UNIQUE (project_id, emp_id)
);

CREATE TABLE expense_transactions (
    tx_id TEXT PRIMARY KEY,
    project_id TEXT NOT NULL,
    requester_emp_id TEXT NOT NULL,
    approver_emp_id TEXT NOT NULL,
    category TEXT NOT NULL CHECK (
        category IN ('국내출장', '해외출장', 'GPU클러스터임차', '외주용역', '보안감사', '교육훈련')
    ),
    destination_city TEXT,
    nights INTEGER NOT NULL DEFAULT 0,
    amount_krw INTEGER NOT NULL,
    approval_status TEXT NOT NULL CHECK (approval_status IN ('승인완료', '결재대기', '반려')),
    tx_date TEXT NOT NULL,
    description TEXT NOT NULL,
    FOREIGN KEY (project_id) REFERENCES projects(project_id),
    FOREIGN KEY (requester_emp_id) REFERENCES employees(emp_id),
    FOREIGN KEY (approver_emp_id) REFERENCES employees(emp_id)
);

CREATE TABLE gpu_cluster_allocations (
    allocation_id TEXT PRIMARY KEY,
    project_id TEXT NOT NULL,
    managed_by_dept_code TEXT NOT NULL,
    gpu_model TEXT NOT NULL CHECK (
        gpu_model IN ('NVIDIA H100-80GB', 'NVIDIA A100-80GB', 'NVIDIA L40S-48GB')
    ),
    node_count INTEGER NOT NULL,
    gpus_per_node INTEGER NOT NULL DEFAULT 8,
    serving_engine TEXT NOT NULL CHECK (
        serving_engine IN ('vLLM (PagedAttention)', 'TGI', 'TensorRT-LLM', 'Triton')
    ),
    kv_cache_waste_pct REAL NOT NULL,
    avg_utilization_pct REAL NOT NULL,
    monthly_cost_krw INTEGER NOT NULL,
    region TEXT NOT NULL CHECK (region IN ('kr-central-1', 'ap-northeast-2')),
    FOREIGN KEY (project_id) REFERENCES projects(project_id),
    FOREIGN KEY (managed_by_dept_code) REFERENCES departments(dept_code)
);

CREATE TABLE department_budgets (
    budget_id TEXT PRIMARY KEY,
    fiscal_year INTEGER NOT NULL,
    dept_code TEXT NOT NULL,
    account_code TEXT NOT NULL CHECK (
        account_code IN ('ACC-5101', 'ACC-5102', 'ACC-5201', 'ACC-5301', 'ACC-5401', 'ACC-5501')
    ),
    category TEXT NOT NULL CHECK (
        category IN ('국내출장', '해외출장', 'GPU클러스터임차', '외주용역', '보안감사', '교육훈련')
    ),
    allocated_krw INTEGER NOT NULL,
    spent_krw INTEGER NOT NULL,
    as_of_date TEXT NOT NULL,
    FOREIGN KEY (dept_code) REFERENCES departments(dept_code),
    UNIQUE (fiscal_year, dept_code, category)
);

CREATE INDEX idx_emp_dept ON employees(dept_code);
CREATE INDEX idx_emp_manager ON employees(manager_emp_id);
CREATE INDEX idx_proj_lead_dept ON projects(lead_dept_code);
CREATE INDEX idx_proj_members_proj ON project_members(project_id);
CREATE INDEX idx_proj_members_emp ON project_members(emp_id);
CREATE INDEX idx_tx_project ON expense_transactions(project_id);
CREATE INDEX idx_tx_status ON expense_transactions(approval_status);
CREATE INDEX idx_tx_category ON expense_transactions(category);
CREATE INDEX idx_gpu_project ON gpu_cluster_allocations(project_id);
CREATE INDEX idx_budget_dept ON department_budgets(dept_code);
"""


